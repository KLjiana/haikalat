package com.kaleblangley.haikalat.subsystems.postprocess.smaa;

import com.kaleblangley.haikalat.backend.GlException;
import com.kaleblangley.haikalat.backend.GlResource;
import com.kaleblangley.haikalat.backend.shader.ShaderProgram;
import com.kaleblangley.haikalat.backend.texture.Texture2D;
import com.kaleblangley.haikalat.core.command.CommandBuffer;
import com.kaleblangley.haikalat.subsystems.postprocess.ScreenQuad;
import com.kaleblangley.haikalat.util.DirectBuffers;

import static org.lwjgl.opengl.GL11.GL_TRIANGLES;
import static org.lwjgl.opengl.GL30.GL_R8;
import static org.lwjgl.opengl.GL30.GL_RG8;

/**
 * Owner of the SMAA 1x programs, full-screen quad and procedural lookup
 * textures (area and search).
 *
 * <p>The three passes follow Jimenez's reference SMAA 1x chain: luma edge
 * detection, blending weight calculation and neighbourhood blending.  The
 * preset is the reference HIGH preset (threshold 0.1, 16 linear search steps,
 * 8 diagonal search steps, 25% corner rounding) and the lookup tables are
 * generated byte-identically from the author's MIT-licensed generators (see
 * {@link SmaaLookupTables} and {@code docs/licenses/smaa.md}).</p>
 *
 * <p>Colour-space contract: the pass consumes and produces display-referred,
 * gamma-encoded RGBA8.  It is assembled after tone mapping and the screen
 * effects, immediately before present/UI compositing.  It is used only for
 * {@code AntiAliasingMode.SMAA}; FXAA and TAA keep their own paths.</p>
 */
public final class SmaaPass implements GlResource {
    public static final int AREA_TEXTURE_WIDTH = SmaaLookupTables.AREA_WIDTH;
    public static final int AREA_TEXTURE_HEIGHT = SmaaLookupTables.AREA_HEIGHT;
    public static final int SEARCH_TEXTURE_WIDTH = SmaaLookupTables.SEARCH_WIDTH;
    public static final int SEARCH_TEXTURE_HEIGHT = SmaaLookupTables.SEARCH_HEIGHT;
    /** SHA-256 of the generated area RG8 payload (author-reference fingerprint). */
    public static final String AREA_TEXTURE_SHA256 = SmaaLookupTables.AREA_SHA256;
    /** SHA-256 of the generated search R8 payload (author-reference fingerprint). */
    public static final String SEARCH_TEXTURE_SHA256 = SmaaLookupTables.SEARCH_SHA256;

    private final ShaderProgram edgeProgram;
    private final ShaderProgram blendProgram;
    private final ShaderProgram neighborhoodProgram;
    private final ScreenQuad quad;
    private final Texture2D areaTexture;
    private final Texture2D searchTexture;
    private boolean closed;

    public SmaaPass() {
        ShaderProgram createdEdge = ShaderProgram.fromResource(SmaaPass.class,
                "/shaders/postprocess/screen-quad.vert",
                "/shaders/postprocess/smaa-edge-detect.frag");
        ShaderProgram createdBlend = null;
        ShaderProgram createdNeighborhood = null;
        ScreenQuad createdQuad = null;
        Texture2D createdArea = null;
        Texture2D createdSearch = null;
        try {
            createdBlend = ShaderProgram.fromResource(SmaaPass.class,
                    "/shaders/postprocess/screen-quad.vert",
                    "/shaders/postprocess/smaa-blend-weights.frag");
            createdNeighborhood = ShaderProgram.fromResource(SmaaPass.class,
                    "/shaders/postprocess/screen-quad.vert",
                    "/shaders/postprocess/smaa-neighborhood-blend.frag");
            createdQuad = new ScreenQuad();
            createdArea = uploadAreaTexture();
            createdSearch = uploadSearchTexture();
        } catch (RuntimeException | Error failure) {
            closeAfterFailure(createdSearch, failure);
            closeAfterFailure(createdArea, failure);
            closeAfterFailure(createdQuad, failure);
            closeAfterFailure(createdNeighborhood, failure);
            closeAfterFailure(createdBlend, failure);
            createdEdge.close();
            throw failure;
        }
        this.edgeProgram = createdEdge;
        this.blendProgram = createdBlend;
        this.neighborhoodProgram = createdNeighborhood;
        this.quad = createdQuad;
        this.areaTexture = createdArea;
        this.searchTexture = createdSearch;
    }

    private static Texture2D uploadAreaTexture() {
        Texture2D texture = Texture2D.createEmpty(AREA_TEXTURE_WIDTH, AREA_TEXTURE_HEIGHT, GL_RG8);
        try {
            texture.uploadRegion(0, 0, AREA_TEXTURE_WIDTH, AREA_TEXTURE_HEIGHT,
                    DirectBuffers.copyOf(SmaaLookupTables.areaRg()));
            return texture;
        } catch (RuntimeException | Error failure) {
            texture.close();
            throw failure;
        }
    }

    private static Texture2D uploadSearchTexture() {
        Texture2D texture = Texture2D.createEmpty(SEARCH_TEXTURE_WIDTH, SEARCH_TEXTURE_HEIGHT, GL_R8);
        try {
            texture.uploadRegion(0, 0, SEARCH_TEXTURE_WIDTH, SEARCH_TEXTURE_HEIGHT,
                    DirectBuffers.copyOf(SmaaLookupTables.searchR()));
            return texture;
        } catch (RuntimeException | Error failure) {
            texture.close();
            throw failure;
        }
    }

    /** First pass: writes the RG edge mask into the current target. */
    public CommandBuffer recordEdgeDetection(CommandBuffer cmd, int sceneTexture,
                                             int width, int height) {
        ensureOpen();
        prepare(cmd);
        cmd.bindShader(edgeProgram);
        cmd.bindSampler(0, null);
        cmd.bindTexture(0, sceneTexture);
        cmd.setUniformInt(edgeProgram, "uColor", 0);
        cmd.setUniformVec2(edgeProgram, "uInvResolution", 1.0f / width, 1.0f / height);
        draw(cmd);
        return cmd;
    }

    /** Second pass: reads the edge mask, writes RGBA blending weights. */
    public CommandBuffer recordBlendingWeights(CommandBuffer cmd, int edgesTexture,
                                               int width, int height) {
        ensureOpen();
        prepare(cmd);
        cmd.bindShader(blendProgram);
        cmd.bindSampler(0, null);
        cmd.bindSampler(1, null);
        cmd.bindSampler(2, null);
        cmd.bindTexture(0, edgesTexture);
        cmd.bindTexture(1, areaTexture);
        cmd.bindTexture(2, searchTexture);
        cmd.setUniformInt(blendProgram, "uEdges", 0);
        cmd.setUniformInt(blendProgram, "uArea", 1);
        cmd.setUniformInt(blendProgram, "uSearch", 2);
        cmd.setUniformVec2(blendProgram, "uInvResolution", 1.0f / width, 1.0f / height);
        cmd.setUniformVec2(blendProgram, "uResolution", width, height);
        draw(cmd);
        return cmd;
    }

    /** Third pass: blends the scene colour with the selected neighbour. */
    public CommandBuffer recordNeighborhoodBlending(CommandBuffer cmd, int sceneTexture,
                                                    int blendTexture, int width, int height) {
        ensureOpen();
        prepare(cmd);
        cmd.bindShader(neighborhoodProgram);
        cmd.bindSampler(0, null);
        cmd.bindSampler(1, null);
        cmd.bindTexture(0, sceneTexture);
        cmd.bindTexture(1, blendTexture);
        cmd.setUniformInt(neighborhoodProgram, "uColor", 0);
        cmd.setUniformInt(neighborhoodProgram, "uBlend", 1);
        cmd.setUniformVec2(neighborhoodProgram, "uInvResolution", 1.0f / width, 1.0f / height);
        draw(cmd);
        return cmd;
    }

    private void prepare(CommandBuffer cmd) {
        cmd.enableBlend(false);
        cmd.enableDepthTest(false);
        cmd.enableCullFace(false);
    }

    private void draw(CommandBuffer cmd) {
        cmd.bindVertexArray(quad.id());
        cmd.drawArrays(GL_TRIANGLES, 0, 6);
        cmd.enableDepthTest(true);
    }

    @Override
    public int id() {
        return edgeProgram.id();
    }

    @Override
    public boolean isClosed() {
        return closed;
    }

    @Override
    public void close() {
        if (closed) {
            return;
        }
        closed = true;
        RuntimeException failure = null;
        failure = closeCollecting(searchTexture, failure);
        failure = closeCollecting(areaTexture, failure);
        failure = closeCollecting(quad, failure);
        failure = closeCollecting(neighborhoodProgram, failure);
        failure = closeCollecting(blendProgram, failure);
        failure = closeCollecting(edgeProgram, failure);
        if (failure != null) {
            throw failure;
        }
    }

    private static void closeAfterFailure(AutoCloseable resource, Throwable failure) {
        if (resource == null) {
            return;
        }
        try {
            resource.close();
        } catch (Exception cleanupFailure) {
            failure.addSuppressed(cleanupFailure);
        }
    }

    private static RuntimeException closeCollecting(AutoCloseable resource,
                                                    RuntimeException failure) {        if (resource == null) {
            return failure;
        }
        try {
            resource.close();
        } catch (Exception closeFailure) {
            RuntimeException runtime = closeFailure instanceof RuntimeException existing
                    ? existing
                    : new IllegalStateException("Failed to close SMAA resource", closeFailure);
            if (failure == null) {
                return runtime;
            }
            failure.addSuppressed(runtime);
        }
        return failure;
    }

    private void ensureOpen() {
        if (closed) {
            throw new GlException("SMAA pass is closed");
        }
    }
}
